import type {
  ExtensionAPI,
  ExtensionContext,
} from "@earendil-works/pi-coding-agent";
import { getMarkdownTheme } from "@earendil-works/pi-coding-agent";
import { Markdown } from "@earendil-works/pi-tui";
import {
  deliveryKey,
  receiptPrefix,
  request,
  streamKaeno,
  threadPath,
} from "./client.ts";
import { cursorSchema, receiptSchema, ReplyDelivery } from "./delivery.ts";

/** One Kaeno server. Each target gets its own provider, model, commands and saved delivery state. */
interface Target {
  /** Provider ID, model ID and prefix of every message type, status key and command. */
  readonly name: string;
  /** Shown above replies that arrive later, for example after a worker report. */
  readonly label: string;
  readonly baseUrl: string;
}

const targets: readonly Target[] = [
  {
    name: "kaeno",
    label: "Kaeno (homelab)",
    baseUrl: process.env.KAENO_URL ?? "http://homelab-kaeno:8080",
  },
  {
    name: "kaeno-local",
    label: "Kaeno (local)",
    baseUrl: process.env.KAENO_LOCAL_URL ?? "http://127.0.0.1:8080",
  },
];

export default function (pi: ExtensionAPI) {
  for (const target of targets) {
    registerTarget(pi, target);
  }
}

function registerTarget(pi: ExtensionAPI, target: Target) {
  const { name, label, baseUrl } = target;
  const replyType = `${name}-reply`;
  const cursorType = `${name}-cursor`;

  // These are replies already generated by Kaeno after it receives a worker report,
  // not raw worker output and not input that should trigger another model call.
  pi.registerMessageRenderer(replyType, (message, { outputPad }) => {
    const text =
      typeof message.content === "string"
        ? message.content
        : message.content
            .filter((part) => part.type === "text")
            .map((part) => part.text)
            .join("\n");
    return new Markdown(
      `**${label}**\n\n${text}`,
      outputPad,
      0,
      getMarkdownTheme(),
    );
  });

  let active:
    | { session: string; inbox: ReplyDelivery; timer?: NodeJS.Timeout }
    | undefined;
  let selectedProvider: string | undefined;

  function stop() {
    if (active) {
      clearInterval(active.timer);
      active.inbox.close();
      active = undefined;
    }
  }

  async function start(ctx: ExtensionContext) {
    stop();
    selectedProvider = ctx.model?.provider;
    const session = ctx.sessionManager.getSessionId();
    const key = deliveryKey(baseUrl, session);
    const prefix = receiptPrefix(baseUrl, session);
    let after: number | "latest" = 0;
    let savedCursor = false;
    let legacy = false;
    // The remote thread belongs to this session, not its active Pi branch.
    // /tree must not rewind the delivery cursor or replay already displayed replies.
    for (const entry of ctx.sessionManager.getEntries()) {
      if (entry.type === "custom" && entry.customType === cursorType) {
        const parsed = cursorSchema.safeParse(entry.data);
        if (parsed.success && parsed.data.key === key) {
          after = Math.max(after, parsed.data.after);
          savedCursor = true;
        }
      }
      if (
        entry.type === "message" &&
        entry.message.role === "assistant" &&
        entry.message.provider === name &&
        !entry.message.responseId
      ) {
        legacy = true;
      }
    }
    // Old versions replayed the whole history without recording IDs. Baseline once,
    // before new requests are admitted, rather than replaying those errors/replies.
    if (!savedCursor && legacy) {
      after = "latest";
    }
    const inbox = new ReplyDelivery(baseUrl, session, {
      after,
      canDeliver: () => selectedProvider === name && ctx.isIdle(),
      displayed: () => {
        const ids = new Set<number>();
        for (const entry of ctx.sessionManager.getEntries()) {
          if (
            entry.type === "message" &&
            entry.message.role === "assistant" &&
            entry.message.responseId?.startsWith(prefix)
          ) {
            const id = Number(entry.message.responseId.slice(prefix.length));
            if (Number.isSafeInteger(id) && id > 0) {
              ids.add(id);
            }
          }
          if (
            entry.type === "custom_message" &&
            entry.customType === replyType
          ) {
            const parsed = receiptSchema.safeParse(entry.details);
            if (parsed.success && parsed.data.key === key) {
              ids.add(parsed.data.id);
            }
          }
        }
        return ids;
      },
      deliver: (reply) =>
        pi.sendMessage(
          {
            customType: replyType,
            content: reply.text,
            display: true,
            details: { key, id: reply.id },
          },
          { triggerTurn: false },
        ),
      checkpoint: (next) => pi.appendEntry(cursorType, { key, after: next }),
      truncated: () =>
        ctx.ui.notify(
          `${label} pruned older unread replies; showing those still available.`,
          "warning",
        ),
    });
    const watcher: {
      session: string;
      inbox: ReplyDelivery;
      timer?: NodeJS.Timeout;
    } = { session, inbox };
    active = watcher;
    let disconnected = false;
    const status = (failed: boolean) => {
      if (active === watcher && disconnected !== failed) {
        disconnected = failed;
        ctx.ui.setStatus(
          name,
          failed ? `${label} unreachable; retrying delivery` : undefined,
        );
      }
    };
    const check = async () => {
      try {
        await inbox.poll();
        status(false);
      } catch {
        if (selectedProvider === name) {
          status(true);
        }
      }
    };
    if (selectedProvider === name) {
      try {
        await inbox.initialize();
      } catch {
        status(true);
      }
    }
    // Delay visible delivery until the host has attached its session listeners.
    // Emitting during session_start loses RPC events on startup/resume.
    if (active === watcher) {
      watcher.timer = setInterval(() => void check(), 1000);
      watcher.timer.unref();
    }
  }

  pi.on("session_start", (_event, ctx) => start(ctx));
  pi.on("session_tree", (_event, ctx) => start(ctx));
  pi.on("session_shutdown", () => stop());
  pi.on("model_select", (event) => {
    selectedProvider = event.model.provider;
  });

  pi.registerProvider(name, {
    baseUrl,
    // Pi requires a credential to list the model; the Kaeno API is unauthenticated.
    apiKey: "none",
    api: `${name}-thread`,
    models: [
      {
        id: name,
        name,
        reasoning: false,
        input: ["text"],
        cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 },
        contextWindow: 1_000_000,
        maxTokens: 64_000,
      },
    ],
    streamSimple: (model, context, options) =>
      streamKaeno(baseUrl, model, context, options, () =>
        active && active.session === options?.sessionId
          ? active.inbox.initialize()
          : Promise.resolve(),
      ),
  });

  pi.registerCommand(`${name}-replies`, {
    description: `Fetch unread ${label} replies now (also delivered automatically)`,
    handler: async (_args, ctx) => {
      if (ctx.model?.provider !== name) {
        ctx.ui.notify(`Select the ${name} model first.`, "info");
        return;
      }
      if (!active || active.session !== ctx.sessionManager.getSessionId()) {
        await start(ctx);
      }
      const count = await active?.inbox.poll();
      if (!count) {
        ctx.ui.notify(`No unread ${label} replies.`, "info");
      }
    },
  });

  pi.registerCommand(`${name}-stop`, {
    description: `Stop ${label}'s current turn and background work for this session`,
    handler: async (_args, ctx) => {
      await request(
        baseUrl,
        `${threadPath(ctx.sessionManager.getSessionId())}/stop`,
        { method: "POST" },
      );
      ctx.ui.notify(`${label} stop requested`, "info");
    },
  });
}
